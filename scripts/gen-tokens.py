# Emits fluid design tokens that reproduce the original site's measured values at 390/768 (mobile) and 1024/1440 (desktop).
T={ # name: (390, 768, 1024, 1440)
 'fs-h1':(73.996,65.49,82.987,108.29),'fs-h2':(49.696,44.754,55.339,70.04),'fs-h3':(34.792,32.036,38.381,46.58),
 'fs-h4':(22.156,21.253,24.004,26.69),'fs-p':(21.076,20.332,22.775,24.99),'fs-btn':(16.864,16.737,17.983,18.36),
 'fs-btn-l':(18.916,18.488,20.318,21.59),'fs-body':(16.864,16.737,17.983,18.36),
 'pt':(47,30,33,47),'pb':(47,47,51,64),'hero-pt':(76,60,67,95),'hero-pb':(76,77,85,112),
 'logo-w':(62,130,130,130),'hdr-py':(23,46,16.4,23),'pad-x':(23,31,41,58),
}
def interp(a,b,x0,x1,lo,hi):
    if a==b: return f"{a:g}px"
    k=(b-a)/(x1-x0); c=a-k*x0
    # value = c + k*100vw
    return f"clamp({min(lo,hi):.3f}px, calc({c:.4f}px + {k*100:.5f}vw), {max(lo,hi):.3f}px)"
m=[];d=[]
for n,(a,b,c,e) in T.items():
    m.append(f"  --{n}: {interp(a,b,390,768,a,b)};")
    # desktop: extrapolate down to 800 and hold at 1440
    k=(e-c)/416; lo=c-k*224
    d.append(f"  --{n}: {interp(c,e,1024,1440,lo,e)};")
css="/* generated by scripts/gen-tokens.py — do not edit */\n:root{\n"+"\n".join(m)+"\n}\n@media (min-width:800px){\n:root{\n"+"\n".join(d)+"\n}\n}\n"
open('src/styles/tokens.css','w').write(css); print(css[:900])
